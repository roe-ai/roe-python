class ManualWrapperParityError(ValueError):
    """Raised when a ``manual`` operation has no matching hand-written method."""


def _load_contract() -> dict[str, Any]:
    yaml = YAML(typ="safe")
    data = yaml.load(CONTRACT_PATH.read_text())
    if not isinstance(data, dict) or not isinstance(data.get("apis"), dict):
        raise ValueError(f"{CONTRACT_PATH} must contain an 'apis' mapping")
    return data


def _load_readme_block() -> str:
    yaml = YAML(typ="safe")
    data = yaml.load(README_BLOCKS_PATH.read_text(encoding="utf-8"))
    try:
        block = data["blocks"]["generated_friendly_apis"]["python"]
    except (KeyError, TypeError) as exc:
        raise ValueError(
            f"{README_BLOCKS_PATH} must contain blocks.generated_friendly_apis.python"
        ) from exc
    if not isinstance(block, str) or not block.strip():
        raise ValueError(
            f"{README_BLOCKS_PATH} blocks.generated_friendly_apis.python must be a non-empty string"
        )
    return block.strip()


def _replace_marked_block(
    readme: str,
    *,
    start_marker: str,
    end_marker: str,
    replacement: str,
) -> str:
    block = f"{start_marker}\n{replacement.strip()}\n{end_marker}"
    pattern = re.compile(
        rf"{re.escape(start_marker)}.*?{re.escape(end_marker)}",
        re.DOTALL,
    )
    updated, count = pattern.subn(block, readme, count=1)
    if count != 1:
        raise ValueError(
            f"{README_PATH} must contain {start_marker} and {end_marker}"
        )
    return updated


def _load_project_version() -> str:
    data = tomllib.loads((ROOT_DIR / "pyproject.toml").read_text(encoding="utf-8"))
    version = data.get("project", {}).get("version")
    if not isinstance(version, str) or not version:
        raise ValueError("pyproject.toml must contain project.version")
    return version


